/// Text in `lang`, English when missing; {placeholders} filled from `args`.
String tr(String lang, String key, [Map<String, Object?> args = const {}]) {
  var text = _s[lang]?[key] ?? _s['en']![key] ?? key;
  args.forEach((k, v) => text = text.replaceAll('{$k}', '${v ?? ''}'));
  return text;
}

/// Every language has every key (checked by test/i18n_test.dart).
Set<String> keysFor(String lang) => _s[lang]!.keys.toSet();

/// Current app language, shared by all screens.
final ValueNotifier<String> appLang = ValueNotifier('en');

String t(String key, [Map<String, Object?> args = const {}]) => tr(appLang.value, key, args);
